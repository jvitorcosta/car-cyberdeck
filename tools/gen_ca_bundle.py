"""Generate src/net/ca_bundle.inc: the root certificates the deck trusts for Spotify, in the
format of the ESP32's bundle checker (WiFiClientSecure::setCACertBundle, esp_crt_bundle.c):
  u16 count, then per root: u16 subject length, u16 key length, subject DER, public key DER
(big-endian), sorted by subject because the checker finds a root by binary search.

Run: python tools/gen_ca_bundle.py [cacert.pem]   (output is committed)
Input: Mozilla's root list as published by curl (https://curl.se/ca/cacert.pem), downloaded
when no file is given. Only the roots in ROOTS are kept: the two Spotify hosts' current roots
and the likeliest replacements, so a CA change on Spotify's side doesn't take the deck down.
Check the current chains with:
  openssl s_client -connect api.spotify.com:443 -servername api.spotify.com -showcerts
Standard library only.
"""
import base64
import os
import re
import sys
import urllib.request

ROOTS = [
    "DigiCert Global Root G2",                    # api.spotify.com (2026-10)
    "Starfield Root Certificate Authority - G2",  # accounts.spotify.com via Certainly (2026-10)
    "DigiCert Global Root G3",
    "Certainly Root R1",
    "Certainly Root E1",
    "ISRG Root X1",
    "GTS Root R1",
]
URL = "https://curl.se/ca/cacert.pem"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "net", "ca_bundle.inc")


def der_item(buf, pos):
    """(tag, start of the whole item, start of the content, end) of the DER item at pos."""
    tag = buf[pos]
    n = buf[pos + 1]
    hdr = 2
    if n & 0x80:
        k = n & 0x7F
        n = int.from_bytes(buf[pos + 2:pos + 2 + k], "big")
        hdr += k
    return tag, pos, pos + hdr, pos + hdr + n


def subject_and_key(cert):
    """Raw subject Name and SubjectPublicKeyInfo of an X.509 certificate (DER)."""
    _, _, c, _ = der_item(cert, 0)           # Certificate
    _, _, p, _ = der_item(cert, c)           # tbsCertificate
    fields = []
    while len(fields) < 7:
        tag, start, _, end = der_item(cert, p)
        fields.append((tag, start, end))
        p = end
    if fields[0][0] == 0xA0:                 # [0] version present
        fields = fields[1:]
    # serial, signature, issuer, validity, subject, subjectPublicKeyInfo
    _, s0, s1 = fields[4]
    _, k0, k1 = fields[5]
    return cert[s0:s1], cert[k0:k1]


def load(pem_text):
    """{name: DER} for every certificate in a curl-style bundle (name on the line before)."""
    out = {}
    for m in re.finditer(r"^([^\n#=][^\n]*)\n=+\n-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----",
                         pem_text, re.S | re.M):
        out[m.group(1).strip()] = base64.b64decode("".join(m.group(2).split()))
    return out


def main():
    if len(sys.argv) > 1:
        text = open(sys.argv[1], encoding="utf-8").read()
    else:
        text = urllib.request.urlopen(URL, timeout=30).read().decode("utf-8")
    certs = load(text)
    missing = [n for n in ROOTS if n not in certs]
    if missing:
        sys.exit("not in the root list: " + ", ".join(missing))
    entries = sorted(subject_and_key(certs[n]) + (n,) for n in ROOTS)
    blob = bytearray(len(entries).to_bytes(2, "big"))
    for subject, key, _ in entries:
        blob += len(subject).to_bytes(2, "big") + len(key).to_bytes(2, "big") + subject + key
    lines = ["// Generated by tools/gen_ca_bundle.py from Mozilla's root list. Do not edit.",
             "// Roots: " + "; ".join(n for _, _, n in entries),
             "#pragma once",
             "#include <cstdint>",
             "static const uint8_t CA_BUNDLE[%d] = {" % len(blob)]
    for i in range(0, len(blob), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in blob[i:i + 16]) + ",")
    lines.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d roots, %d bytes -> %s" % (len(entries), len(blob), os.path.relpath(OUT)))


if __name__ == "__main__":
    main()
