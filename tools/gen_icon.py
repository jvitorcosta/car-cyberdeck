"""Generate src/black/net/icon.inc: the phone remote's Home Screen icon (apple-touch-icon, 180x180
PNG). An original design drawn here: a speaker with sound waves over a road stripe, in the
page's colours. Output is committed. Run: python tools/gen_icon.py   (standard library only)
"""
import math
import os
import struct
import zlib

N = 180
BG = (16, 24, 32)          # page background #101820
FG = (232, 160, 32)        # button orange #e8a020
ROAD = (64, 72, 80)
LINE = (248, 248, 216)     # page text colour #f8f8d8
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "black", "net", "icon.inc")


def inside_speaker(x, y):
    # Box (the magnet) and a cone opening to the right.
    if 38 <= x <= 58 and 66 <= y <= 98:
        return True
    if 58 <= x <= 86:
        half = 16 + (x - 58) * 0.9          # cone widens from 16 to ~41 px half-height
        return abs(y - 82) <= half
    return False


def on_wave(x, y):
    # Three arcs centred on the cone's mouth.
    d = math.hypot(x - 84, y - 82)
    if x < 92:
        return False
    ang = abs(math.degrees(math.atan2(y - 82, x - 84)))
    if ang > 50:
        return False
    return any(abs(d - r) <= 4.5 for r in (22, 40, 58))


def pixel(x, y):
    # iOS rounds the corners itself; fill the square.
    if 140 <= y <= 166:
        if 74 <= x <= 106 and 150 <= y <= 156:
            return LINE                     # dashed centre line
        if 22 <= x <= 58 and 150 <= y <= 156:
            return LINE
        if 122 <= x <= 158 and 150 <= y <= 156:
            return LINE
        return ROAD
    if inside_speaker(x, y) or on_wave(x, y):
        return FG
    return BG


def png(w, h, rows):
    raw = b"".join(b"\x00" + bytes(c for px in row for c in px) for row in rows)

    def chunk(t, b):
        return struct.pack(">I", len(b)) + t + b + struct.pack(">I", zlib.crc32(t + b) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


data = png(N, N, [[pixel(x, y) for x in range(N)] for y in range(N)])
with open(OUT, "w", encoding="ascii", newline="\n") as f:
    f.write("// Generated by tools/gen_icon.py (original design). Do not edit.\n")
    f.write("static const uint8_t ICON_PNG[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
if len(os.sys.argv) > 1:                    # optional: also save the PNG to look at
    with open(os.sys.argv[1], "wb") as f:
        f.write(data)
print("wrote %s (%d bytes PNG)" % (OUT, len(data)))
